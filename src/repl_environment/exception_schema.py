"""D-RI-CONTAIN item (a): a bounded, structured exception schema for REPL errors.

Threat (intake-2684, arXiv 2602.15945): exception text from a tool or from model code is fed
back into the next prompt and steers the next snippet. A free-text ``f"{type}: {message}"`` is an
instruction channel: the message can be multi-line, carry fake role markers, and be arbitrarily
long. The replacement is a fixed schema,

    <ExceptionType>: {"origin": "tool:peek", "message": "<defanged, capped>", "truncated": false}

whose only free-text field is ``message``: capped (``MESSAGE_CAP`` chars) BEFORE scanning,
run through ``untrusted_text.sanitize_tool_text`` (role markers, fences, data delimiters), and
JSON-encoded (``ensure_ascii``), so it can never contain a newline, a line-start marker or a raw
control character. ``ExceptionType`` is restricted to an identifier and ``origin`` to a closed
vocabulary (``repl`` | ``model_code`` | ``tool:<identifier>``). The hint, which is generated by
the REPL itself and trusted, is appended OUTSIDE the schema.

Flag: ``ORCHESTRATOR_REPL_TOOL_ARG_VALIDATION`` / ``ORCHESTRATOR_REPL_CHILD_LANE`` (or the runtime
flags of the same names). Flag off: ``format_exception`` returns exactly the historical
``"{type}: {message}{hint}"``. The prompt-side label (``wrap_untrusted``) is unchanged and still applies.
"""

from __future__ import annotations

import json
import re

MESSAGE_CAP = 240
_TYPE_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_.]{0,79}$")
_ORIGIN_RE = re.compile(r"^(?:repl|model_code|tool:[A-Za-z_][A-Za-z0-9_]{0,63})$")


def enabled() -> bool:
    from src.repl_environment import tool_arg_validation

    return tool_arg_validation.flag_enabled()


def render(etype: str, message: str, origin: str = "repl", hint: str = "") -> str:
    """The structured rendering (always; the flag is applied by ``format_exception``)."""
    from src.security.untrusted_text import sanitize_tool_text

    etype = etype if isinstance(etype, str) and _TYPE_RE.match(etype) else "Exception"
    origin = origin if isinstance(origin, str) and _ORIGIN_RE.match(origin) else "repl"
    message = message if isinstance(message, str) else str(message)
    truncated = len(message) > MESSAGE_CAP
    safe = sanitize_tool_text(message[:MESSAGE_CAP])
    body = json.dumps({"origin": origin, "message": safe, "truncated": truncated}, ensure_ascii=True)
    return f"{etype}: {body}{hint}"


def format_exception(exc_or_type: BaseException | str, message: str | None = None, origin: str = "repl",
                     hint: str = "") -> str:
    """Error text for ``ExecutionResult.error``: schema when enabled, else the historical f-string."""
    if isinstance(exc_or_type, BaseException):
        etype, msg = type(exc_or_type).__name__, str(exc_or_type)
    else:
        etype, msg = str(exc_or_type), message or ""
    if not enabled():
        return f"{etype}: {msg}{hint}"
    return render(etype, msg, origin, hint)
